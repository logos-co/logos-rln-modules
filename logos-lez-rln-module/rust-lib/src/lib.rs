    // TTL eviction: a stale entry (Failed registration awaiting retry) must
    // fall out of the dedup map, while a fresh entry keeps deduping.
    #[test]
    fn reg_in_flight_entries_expire_after_ttl() {
        let stale_key = [0xaa_u8; 32];
        let fresh_key = [0xbb_u8; 32];
        let Some(back_dated) =
            Instant::now().checked_sub(REG_IN_FLIGHT_TTL + Duration::from_secs(1))
        else {
            eprintln!("reg_in_flight ttl test: uptime too short to back-date; skipping");
            return;
        };
        reg_in_flight(|m| {
            m.insert(stale_key, (RegisterReply::refused("stale"), back_dated));
            m.insert(fresh_key, (RegisterReply::refused("fresh"), Instant::now()));
        });
        reg_in_flight(|m| {
            assert!(!m.contains_key(&stale_key), "stale entry must be evicted");
            assert_eq!(
                m.get(&fresh_key).map(|(r, _)| r),
                Some(&RegisterReply::refused("fresh"))
            );
            m.remove(&fresh_key);
        });
    }

    // Pins the preflight arithmetic: a balance must cover the price plus the
    // fee reserve.
    #[test]
    fn can_afford_requires_the_balance_to_cover_price_plus_fee_reserve() {
        let (price, reserve) = (1_000_u128, 50_u128);
        // Exactly price + reserve is enough; one less is not.
        assert!(can_afford(1_050, price, reserve));
        assert!(!can_afford(1_049, price, reserve));
        // A balance that covers only the price is refused.
        assert!(!can_afford(1_000, price, reserve));
        // A balance well above the sum is enough; one well below it is not.
        assert!(can_afford(10_000, price, reserve));
        assert!(!can_afford(100, price, reserve));
        // Saturating sums never wrap.
        assert!(!can_afford(u128::MAX - 1, u128::MAX, 1));
        assert!(can_afford(u128::MAX, u128::MAX, 1));
    }

    // Pins proofs_with_roots_json to the byte output of the string
    // round-trip (serialize → re-parse as Value → insert valid_roots →
    // re-serialize) that defines the frozen wire format.
    #[test]
    fn augmented_proofs_match_json_roundtrip() {
        let proofs = vec![native::ProofJson {
            leaf: "aa".repeat(32),
            root: "bb".repeat(32),
            leaf_index: 5,
            depth: 2,
            path_elements: vec!["cc".repeat(32), "dd".repeat(32)],
            path_indices: vec![1, 0],
        }];
        let roots_array = roots_to_json_array(&[[0xEE; 32]]);

        let legacy_json = serde_json::to_string(&proofs).unwrap();
        let legacy_parsed = serde_json::from_str::<serde_json::Value>(&legacy_json)
            .ok()
            .and_then(|v| v.as_array().cloned())
            .unwrap_or_default();
        let legacy: Vec<serde_json::Value> = legacy_parsed
            .into_iter()
            .map(|p| {
                let mut obj = p.as_object().cloned().unwrap_or_default();
                obj.insert("valid_roots".to_string(), roots_array.clone());
                serde_json::Value::Object(obj)
            })
            .collect();
        let legacy_str = serde_json::Value::Array(legacy).to_string();

        let current_str = proofs_with_roots_json(&proofs, &roots_array);
        assert_eq!(current_str, legacy_str);
        // Alphabetical keys, valid_roots last.
        assert!(current_str.starts_with("[{\"depth\":2,\"leaf\":\"aa"));
        assert!(current_str.contains("\"root\":\"bb"));
        let expected_tail = format!("\"valid_roots\":[\"{}\"]}}]", "ee".repeat(32));
        assert!(current_str.ends_with(&expected_tail));
    }

    // Several proofs share one roots array; every proof carries all of it.
    // Pins the full text (key order, number widths, escapes, empty paths)
    // and its equality with the round-trip, plus the empty list.
    #[test]
    fn several_augmented_proofs_serialize_to_the_wire_text() {
        let proof =
            |leaf: &str, root: &str, leaf_index, depth, elements: &[&str], indices: &[u8]| {
                native::ProofJson {
                    leaf: leaf.into(),
                    root: root.into(),
                    leaf_index,
                    depth,
                    path_elements: elements.iter().map(|e| (*e).to_owned()).collect(),
                    path_indices: indices.to_vec(),
                }
            };
        let proofs = vec![
            proof("a1", "r1", 0, 1, &["p1", "p2"], &[1, 0]),
            proof("a\"2\\", "r2", u64::MAX, u32::MAX, &[], &[]),
            proof("é\u{1}", "", 7, 3, &["x"], &[255]),
        ];
        let roots_array = serde_json::json!(["e1", "e2"]);
        let current = proofs_with_roots_json(&proofs, &roots_array);
        assert_eq!(
            current,
            r#"[{"depth":1,"leaf":"a1","leaf_index":0,"path_elements":["p1","p2"],"path_indices":[1,0],"root":"r1","valid_roots":["e1","e2"]},{"depth":4294967295,"leaf":"a\"2\\","leaf_index":18446744073709551615,"path_elements":[],"path_indices":[],"root":"r2","valid_roots":["e1","e2"]},{"depth":3,"leaf":"é\u0001","leaf_index":7,"path_elements":["x"],"path_indices":[255],"root":"","valid_roots":["e1","e2"]}]"#
        );
        let roundtrip: Vec<serde_json::Value> = proofs
            .iter()
            .map(|p| {
                let mut obj = match serde_json::to_value(p).unwrap() {
                    serde_json::Value::Object(obj) => obj,
                    other => panic!("a proof serializes to an object, got {other}"),
                };
                // OWNERSHIP: the round-trip reference puts an owned copy in every object.
                obj.insert("valid_roots".to_owned(), roots_array.clone());
                serde_json::Value::Object(obj)
            })
            .collect();
        assert_eq!(current, serde_json::Value::Array(roundtrip).to_string());
        assert_eq!(proofs_with_roots_json(&[], &roots_array), "[]");
    }

