/// The account `id` names (64-hex or base58), or `None` (logged) when it is
/// no account id.
fn resolve_account(id: &str) -> Option<[u8; 32]> {
    let account = hex::account_id_bytes(id);
    if account.is_none() {
        eprintln!("{id} is neither 32-byte hex nor a base58 account id");
    }
    account
}

/// `canonical_account_hex`, or "" (logged) when `id` is no account id.
fn resolve_account_id(id: &str) -> String {
    resolve_account(id)
        .map(|account| bytes_to_hex(&account))
        .unwrap_or_default()
}

/// The native token program's id: the actor whose state on an account is its
/// native balance (`NATIVE_TOKEN_PROGRAM_ID`).
const NATIVE_TOKEN_PROGRAM: [u8; 32] = [0; 32];

/// Tri-state fetch: Present / legitimately Absent (no such account, no such
/// actor state, or an empty one) / Error (the read failed). Logs nothing.
enum FetchOutcome {
    Present(Vec<u8>),
    Absent,
    Error,
}

/// Every actor state of an account as `(program, data)`, or `None` when the
/// read failed. An account that does not exist reads as no states.
///
/// An account's data is kept per program, so "the account's data" is not one
/// thing: callers name the program whose state they mean.
fn fetch_actor_states(account_id: &[u8; 32]) -> Option<Vec<([u8; 32], Vec<u8>)>> {
    match wallet::read_account(account_id) {
        wallet::AccountRead::Present(states) => Some(states),
        wallet::AccountRead::Absent => Some(Vec::new()),
        wallet::AccountRead::Error => None,
    }
}

fn fetch_shard_tri_state(account_id: &[u8; 32], program: &[u8; 32]) -> FetchOutcome {
    let Some(states) = fetch_actor_states(account_id) else {
        return FetchOutcome::Error;
    };
    match states.into_iter().find(|(p, _)| p == program) {
        Some((_, data)) if !data.is_empty() => FetchOutcome::Present(data),
        _ => FetchOutcome::Absent,
    }
}

/// Some(data) only for a populated state; logs nothing. Used where "not yet
/// present" is an expected state — today only register_member's idempotency
/// pre-check.
fn fetch_shard_quiet(account_id: &[u8; 32], program: &[u8; 32]) -> Option<Vec<u8>> {
    match fetch_shard_tri_state(account_id, program) {
        FetchOutcome::Present(data) => Some(data),
        _ => None,
    }
}

/// Loud fetch of one program's state on an account: logs each failure mode.
fn fetch_shard(account_id: &[u8; 32], program: &[u8; 32], who: &str) -> Option<Vec<u8>> {
    match fetch_shard_tri_state(account_id, program) {
        FetchOutcome::Present(data) => Some(data),
        FetchOutcome::Absent => {
            eprintln!(
                "{who}: {} holds no state of program {}",
                bytes_to_hex(account_id),
                bytes_to_hex(program)
            );
            None
        }
        FetchOutcome::Error => {
            eprintln!("{who}: reading {} failed", bytes_to_hex(account_id));
            None
        }
    }
}

/// The resolved config and the two program ids every on-chain entry point
/// needs: the registration program (the config's owner, and the program every
/// PDA hangs off) and the merkle program (whose actor state on `tree_main`
/// holds the tree).
struct RlnConfigContext {
    config_account: [u8; 32],
    config_data: Vec<u8>,
    registration_program: [u8; 32],
    merkle_program: [u8; 32],
}

/// Why a config account cannot serve as a registry here. `status` is the
/// machine-readable kind check_registry reports; `detail` says it for a person.
struct RegistryProblem {
    status: &'static str,
    detail: String,
}

impl RegistryProblem {
    fn new(status: &'static str, detail: String) -> Self {
        Self { status, detail }
    }
}

/// `config_context` for the config account a caller names; problems logged.
fn resolve_config_context(config_account_id: &str, who: &str) -> Option<RlnConfigContext> {
    logged_context(
        config_account(config_account_id).and_then(|config| config_context(&config)),
        who,
    )
}

fn logged_context(
    context: Result<RlnConfigContext, RegistryProblem>,
    who: &str,
) -> Option<RlnConfigContext> {
    context.map_err(|p| eprintln!("{who}: {}", p.detail)).ok()
}

/// The config account a caller names, or the `invalid` problem.
fn config_account(config_account_id: &str) -> Result<[u8; 32], RegistryProblem> {
    resolve_account(config_account_id).ok_or_else(|| {
        RegistryProblem::new(
            "invalid",
            format!("'{config_account_id}' is not an account id"),
        )
    })
}

fn config_context(config: &[u8; 32]) -> Result<RlnConfigContext, RegistryProblem> {
    let config_hex = bytes_to_hex(config);
    if let Some(reason) = network_conflict(wallet::bound_network().as_deref(), &config_hex) {
        return Err(RegistryProblem::new("network_conflict", reason));
    }
    let Some(states) = fetch_actor_states(config) else {
        return Err(RegistryProblem::new(
            "unreachable",
            format!("could not read config account {config_hex} from the sequencer"),
        ));
    };
    // A program's id is the header account its deployer created, not
    // derivable from anything a registry id carries. The config is the
    // registration program's PDA and holds exactly one program's state — that
    // program's — so its key IS the registration program id. A native balance
    // (someone sent it tokens) is not a program and is skipped.
    let mut program_shards = states
        .into_iter()
        .filter(|(p, data)| *p != NATIVE_TOKEN_PROGRAM && !data.is_empty());
    let Some((registration_program, config_data)) = program_shards.next() else {
        // What a reset zone looks like: the URL still answers, every account
        // is gone. The same answer for a registry that never existed here.
        return Err(RegistryProblem::new(
            "not_deployed",
            format!(
                "config account {config_hex} holds no program state on this chain — the registry \
                 is not deployed here (the network may have been reset)"
            ),
        ));
    };
    if program_shards.next().is_some() {
        return Err(RegistryProblem::new(
            "unexpected_layout",
            format!("config account {config_hex} holds more than one program's state"),
        ));
    }
    // The one place a config account is admitted, and so the one place its
    // generation is checked. Every field below is read by byte offset and
    // ConfigState carries no version discriminator, so a config from another
    // program generation does not fail to decode — it decodes to a plausible
    // wrong treasury and a plausible wrong price. Length is the only signal.
    if config_data.len() != native::CONFIG_STATE_SIZE {
        return Err(RegistryProblem::new(
            "wrong_generation",
            format!(
                "config state is {} bytes, expected {} — this is a config from a different \
                 program generation, not a short read",
                config_data.len(),
                native::CONFIG_STATE_SIZE,
            ),
        ));
    }
    let merkle_program =
        native::config_field_32(&config_data, native::CONFIG_OFFSET_MERKLE_PROGRAM_ID);
    Ok(RlnConfigContext {
        config_account: *config,
        config_data,
        registration_program,
        merkle_program,
    })
}

/// Why a config account must not be read through this wallet, if it must not.
///
/// A home bound to one network cannot serve a registry the table places on
/// another: the account either does not exist there or, worse, is someone
/// else's. Only a recorded binding is checked — an operator-configured home
/// has no network name to compare — and only a config the table knows, since
/// an unlisted registry may well live on the bound chain.
fn network_conflict(bound: Option<&str>, config_hex: &str) -> Option<String> {
    let bound = bound?;
    let listed = networks::network_of_config(config_hex)?;
    (listed.reference != bound).then(|| {
        format!(
            "config account {config_hex} is on network {}, but this wallet is bound to {bound}",
            listed.reference
        )
    })
}

/// The account a transaction declares as its fee payer: the one the wallet
/// resolved at bring-up from LEZ_RLN_PAYER, the payer record, or derivation.
/// A bring-up that resolves none never reaches Ready, so nothing is sent.
fn fee_payer_hex() -> &'static str {
    wallet::payer_hex()
}

/// Submit one public transaction through the module's own wallet: `message`
/// goes to the actor `mentions[root]` selects. `Err(why)` = the sequencer
/// accepted nothing, already logged.
fn send_generic_tx(
    who: &str,
    mentions: &[wallet::Mention],
    root: usize,
    message: &[u8],
    payer_hex: &str,
) -> Result<wallet::SendResult, String> {
    let accepted = wallet::send_generic_public_transaction(mentions, root, message, payer_hex)
        .ok_or_else(|| "no reply from the wallet".to_string())
        .and_then(wallet::SendResult::accepted);
    if let Err(why) = &accepted {
        eprintln!("{who}: transaction failed: {why}");
    }
    accepted
}

fn derive_register_plan(
    ctx: &RlnConfigContext,
    id_commitment: &[u8; 32],
    who: &str,
) -> Option<RlnRegisterPlan> {
    let tree_main = match native::tree_main_account_id(&ctx.config_data, &ctx.registration_program)
    {
        Ok(id) => id,
        Err(e) => {
            eprintln!("{who}: derive tree main failed: {e}");
            return None;
        }
    };
    let tree_main_data = fetch_shard(&tree_main, &ctx.merkle_program, who)?;
    match native::register_plan(
        &ctx.config_data,
        &tree_main_data,
        &ctx.registration_program,
        id_commitment,
    ) {
        Ok(plan) => Some(plan),
        Err(e) => {
            eprintln!("{who}: register_plan failed: {e}");
            None
        }
    }
}

/// Chain time in milliseconds: the head block's timestamp, which the registry
/// judges lifecycles by. `None` (logged) when the chain cannot be read.
fn chain_time_ms(who: &str) -> Option<u64> {
    let time = fee_state::head_block_timestamp_ms();
    if time.is_none() {
        eprintln!("{who}: chain time unavailable");
    }
    time
}

/// How far behind the head block's timestamp a `Register` dates itself. The
/// program accepts the message for 900 s from its `now_ms`, but refuses one
/// dated after the block it lands in: the sequencer's clock can step back
/// between the head read and the next block, and a few seconds of slack costs
/// nothing against a window that long.
const CHAIN_TIME_SLACK_MS: u64 = 5_000;

/// The leaf index of a membership that exists, from the tree.
///
/// The merkle program assigns the slot as the registration applies and the
/// membership record does not keep it, so the index is found by looking the
/// member's leaf up in the tree. `None` (logged) when the tree cannot be read
/// or does not hold the leaf — never a guess.
fn membership_leaf_index(
    ctx: &RlnConfigContext,
    membership: &rln_layouts::MembershipState,
    who: &str,
) -> Option<u64> {
    let tree = fetch_tree_shard(ctx, who)?;
    let Some(leaf) = native::registration_leaf(&membership.id_commitment, membership.rate_limit)
    else {
        eprintln!("{who}: the membership's id_commitment is not a field element");
        return None;
    };
    let found = native::find_leaf_index(&tree, &leaf);
    if found.is_none() {
        eprintln!("{who}: the tree holds no leaf for this membership");
    }
    found
}

/// The tree: the merkle program's state on `tree_main` — one read, so the
/// roots and every proof built from it come from the same tree state.
fn fetch_tree_shard(ctx: &RlnConfigContext, who: &str) -> Option<Vec<u8>> {
    let main = match native::tree_main_account_id(&ctx.config_data, &ctx.registration_program) {
        Ok(id) => id,
        Err(e) => {
            eprintln!("{who}: derive tree main failed: {e}");
            return None;
        }
    };
    fetch_shard(&main, &ctx.merkle_program, who)
}

fn roots_to_json_array(roots: &[[u8; 32]]) -> serde_json::Value {
    serde_json::Value::Array(
        roots
            .iter()
            .map(|r| serde_json::Value::String(bytes_to_hex(r)))
            .collect(),
    )
}

/// One proof as the wire carries it: `ProofJson`'s fields plus the shared
/// `valid_roots`, declared in alphabetical order — the frozen wire key order
/// (pinned by `augmented_proofs_match_json_roundtrip` and
/// `several_augmented_proofs_serialize_to_the_wire_text`).
// OWNERSHIP: a serialisation view borrowing the proof and the one roots array every proof shares.
#[derive(serde::Serialize)]
struct ProofWithRoots<'a> {
    depth: u32,
    leaf: &'a str,
    leaf_index: u64,
    path_elements: &'a [String],
    path_indices: &'a [u8],
    root: &'a str,
    valid_roots: &'a serde_json::Value,
}

/// Serialize proofs plus the shared `valid_roots` array to the wire JSON.
fn proofs_with_roots_json(proofs: &[native::ProofJson], roots_array: &serde_json::Value) -> String {
    let augmented: Vec<ProofWithRoots<'_>> = proofs
        .iter()
        .map(|p| ProofWithRoots {
            depth: p.depth,
            leaf: &p.leaf,
            leaf_index: p.leaf_index,
            path_elements: &p.path_elements,
            path_indices: &p.path_indices,
            root: &p.root,
            valid_roots: roots_array,
        })
        .collect();
    serde_json::to_string(&augmented).unwrap_or_default()
}

/// A wire flag that is only ever `true`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct Yes;

impl serde::Serialize for Yes {
    fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        s.serialize_bool(true)
    }
}

/// `register_member`'s answer when it has one ("" is a read failure).
#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize)]
#[serde(untagged)]
enum RegisterReply {
    /// In flight. The placeholder (no `tx_result`) and the accepted
    /// submission share one shape, since the in-flight dedup hands either
    /// back to a repeat caller. `tx_result` is the send result as JSON text.
    Submitted {
        leaf_index: u64,
        pending: Yes,
        rate_limit: u64,
        #[serde(skip_serializing_if = "Option::is_none")]
        tx_result: Option<String>,
    },
    AlreadyRegistered {
        already_registered: Yes,
        leaf_index: u64,
    },
    /// `"<kind>: <reason>"`.
    Refused { error: String },
}

impl RegisterReply {
    fn pending(leaf_index: u64, rate_limit: u64, sent: Option<&wallet::SendResult>) -> Self {
        Self::Submitted {
            leaf_index,
            pending: Yes,
            rate_limit,
            tx_result: sent.map(wallet::SendResult::to_json),
        }
    }

    fn refused(why: impl Into<String>) -> Self {
        Self::Refused { error: why.into() }
    }

    /// Through `serde_json::Value`, whose map orders keys alphabetically:
    /// the key order consumers read.
    fn to_json(&self) -> String {
        serde_json::to_value(self)
            .map(|v| v.to_string())
            .unwrap_or_default()
    }
}

/// Build and send one `Register`, dated by chain time read now. `Err(why)` =
/// not submitted, already logged.
fn submit_register(
    ctx: &RlnConfigContext,
    plan: &RlnRegisterPlan,
    id_commitment: &[u8; 32],
    rate_limit: u64,
    payer_hex: &str,
    who: &str,
) -> Result<wallet::SendResult, String> {
    let Some(payer) = hex_to_bytes32(payer_hex) else {
        eprintln!("{who}: payer {payer_hex} is not 32-byte hex");
        return Err(format!("payer {payer_hex} is not 32-byte hex"));
    };
    // The validity window opens at now_ms, so it is read last, just before
    // sending.
    let now_ms = chain_time_ms(who)
        .ok_or_else(|| "chain time unavailable".to_string())?
        .saturating_sub(CHAIN_TIME_SLACK_MS);
    let message =
        match native::register_build_message(plan, id_commitment, rate_limit, &payer, now_ms) {
            Ok(bytes) => bytes,
            Err(e) => {
                eprintln!("{who}: register_build_message failed: {e}");
                return Err(format!("register_build_message failed: {e}"));
            }
        };
    // Every actor the program touches while handling Register is declared:
    // the config (the message's receiver), the membership it writes for the
    // first time (admitted by its PDA seed), the tree it inserts into, and the
    // two native balances the payment moves between. The payer signs; the
    // treasury must already exist, which preflight_register checks.
    use wallet::MentionKind::{NoSign, Pda, Signer};
    let mention = |account: [u8; 32], program: [u8; 32], kind| wallet::Mention {
        account,
        program,
        kind,
    };
    let mentions = [
        mention(plan.config_account_id, ctx.registration_program, NoSign),
        mention(
            plan.membership_account_id,
            ctx.registration_program,
            Pda {
                program: ctx.registration_program,
                seed: rln_layouts::membership_seed(&plan.tree_id, id_commitment),
            },
        ),
        mention(plan.tree_main_account_id, plan.merkle_program_id, NoSign),
        mention(payer, NATIVE_TOKEN_PROGRAM, Signer),
        mention(plan.treasury_account_id, NATIVE_TOKEN_PROGRAM, NoSign),
    ];
    send_generic_tx(who, &mentions, 0, &message, fee_payer_hex())
}

/// How often the watcher looks at the chain, and how many times a reverted
/// registration is re-sent before the watcher gives up and frees the slot for
/// a later caller.
const REG_WATCH_INTERVAL: Duration = Duration::from_secs(2);
const REG_MAX_RESUBMITS: u32 = 5;
/// How many consecutive polls a transaction the sequencer has never included
/// gets before it counts as dropped (120 s; inclusion takes 60-90 s): a
/// registration signed with a nonce another send consumed first is dropped
/// at the door without a word and would otherwise stay "pending" until the
/// watcher's deadline, never re-sent.
const REG_DROPPED_POLLS: u32 = 60;

struct RegisterWatch {
    config_account: [u8; 32],
    payer_hex: String,
    id_commitment: [u8; 32],
    rate_limit: u64,
    reg_key: [u8; 32],
    tx_hash: String,
}

/// Storage bytes a Register declares beside its gas limit when the fee
/// reserve is sized; the same allowance liblogos_rln_module reserves for.
const REGISTER_DATA_ALLOWANCE: u128 = 100_000;

/// Everything the program would refuse that can be known before signing:
/// rln_core::check_register's argument and capacity checks, that the treasury
/// exists (a declared actor must be admitted, and the treasury's native
/// balance is admitted only by existing), and whether the payer can cover the
/// price plus the fee reserve at the next block's base fee ceiling (skipped
/// when no fee quote can be had — an outage is not a refusal). There is no
/// transaction simulation, so this is the only way to keep a doomed
/// registration from being signed and charged.
fn preflight_register(
    ctx: &RlnConfigContext,
    plan: &RlnRegisterPlan,
    id_commitment: &[u8; 32],
    rate_limit: u64,
    payer_hex: &str,
) -> Result<(), String> {
    native::check_register(
        &ctx.config_data,
        plan.next_leaf_index,
        id_commitment,
        rate_limit,
    )?;
    if let wallet::AccountRead::Absent = wallet::read_account(&plan.treasury_account_id) {
        return Err(format!(
            "treasury_missing: the registry's treasury {} does not exist on this chain; run_setup \
             seeds it",
            bytes_to_hex(&plan.treasury_account_id)
        ));
    }
    let quote = fee_state::fee_quote();
    let ceiling = |key: &str| {
        quote
            .as_ref()
            .and_then(|q| q.get(key))
            .and_then(serde_json::Value::as_u64)
            .map(u128::from)
    };
    let (Some(exec), Some(stor)) = (
        ceiling("next_base_fee_exec_ceiling"),
        ceiling("next_base_fee_stor_ceiling"),
    ) else {
        return Ok(());
    };
    let Some((_, balance)) = wallet::native_balance(payer_hex) else {
        return Ok(());
    };
    let price = plan.price_per_unit.saturating_mul(u128::from(rate_limit));
    let reserve = u128::from(wallet::GAS_LIMIT)
        .saturating_mul(exec)
        .saturating_add(REGISTER_DATA_ALLOWANCE.saturating_mul(stor));
    let needed = price.saturating_add(reserve);
    if !can_afford(balance, price, reserve) {
        return Err(format!(
            "insufficient_balance: payer {payer_hex} holds {balance}, a registration needs {needed} \
             ({price} price + {reserve} fee reserve at the next block's base fee ceiling)"
        ));
    }
    Ok(())
}

fn spawn_register_watch(w: RegisterWatch) {
    let spawned = std::thread::Builder::new()
        .name("lez-rln-register-watch".into())
        .spawn(move || register_watch(w));
    if let Err(e) = spawned {
        eprintln!("register_member: could not start the confirmation watcher: {e}");
    }
}

/// Follow a submitted registration until its membership appears, re-sending it
/// if it reverted.
///
/// A registration the program refuses (its `now_ms` outside the validity
/// window, the registry filled up under it) is still included in a block —
/// charged, with no effect, and nothing sent back to the submitter. So the
/// fate is read from the chain: the membership appearing is success; the
/// transaction in a block without it is a revert, re-planned and re-sent with
/// a fresh `now_ms`, which is exactly what a window revert needs. A
/// transaction the sequencer still holds (deferred on the block gas cap, which
/// fits one registration per block) is left alone: re-sending it would race
/// the original, and the loser pays a full registration's gas for nothing.
///
/// The block's own revert list is not consulted: reading it means fetching
/// and borsh-decoding every transaction in the block, and the membership read
/// answers the same question for one account.
fn register_watch(mut w: RegisterWatch) {
    const WHO: &str = "register_member(watch)";
    let deadline = Instant::now() + REG_IN_FLIGHT_TTL;
    let mut resubmits = 0u32;
    let mut not_included = 0u32;
    while Instant::now() < deadline {
        std::thread::sleep(REG_WATCH_INTERVAL);
        let Some(ctx) = logged_context(config_context(&w.config_account), WHO) else {
            continue;
        };
        let Some(plan) = derive_register_plan(&ctx, &w.id_commitment, WHO) else {
            continue;
        };
        let landed = || {
            fetch_shard_quiet(&plan.membership_account_id, &ctx.registration_program)
                .and_then(|data| native::decode_membership(&data).ok())
        };
        if let Some(m) = landed() {
            match membership_leaf_index(&ctx, &m, WHO) {
                Some(leaf) => eprintln!("{WHO}: registered at leaf {leaf}"),
                None => eprintln!("{WHO}: registered"),
            }
            return;
        }
        match fee_state::tx_included(&w.tx_hash) {
            Some(true) => not_included = 0,
            Some(false) => {
                not_included += 1;
                if not_included < REG_DROPPED_POLLS {
                    continue;
                }
                not_included = 0;
                eprintln!(
                    "{WHO}: tx {} not included after {REG_DROPPED_POLLS} polls — dropped at the door; \
                     re-sending",
                    w.tx_hash
                );
            }
            None => continue,
        }
        // Included: re-read once, in case it applied between the two reads.
        if landed().is_some() {
            continue;
        }
        if resubmits >= REG_MAX_RESUBMITS {
            eprintln!(
                "{WHO}: membership still absent after {REG_MAX_RESUBMITS} re-sends — giving up; \
                 a later register_member call starts afresh"
            );
            reg_in_flight(|m| m.remove(&w.reg_key));
            return;
        }
        // A revert that a fresh now_ms cannot fix (an argument the program
        // refuses, a full registry, a missing treasury, a payer that cannot
        // pay) would revert, and be charged, on every re-send.
        if let Err(why) =
            preflight_register(&ctx, &plan, &w.id_commitment, w.rate_limit, &w.payer_hex)
        {
            eprintln!(
                "{WHO}: tx {} reverted and a re-send would too — not re-sending: {why}",
                w.tx_hash
            );
            reg_in_flight(|m| m.insert(w.reg_key, (RegisterReply::refused(why), Instant::now())));
            return;
        }
        eprintln!(
            "{WHO}: tx {} is in a block but registered nothing — it reverted; re-sending dated \
             by chain time now",
            w.tx_hash
        );
        resubmits += 1;
        let send_result = match submit_register(
            &ctx,
            &plan,
            &w.id_commitment,
            w.rate_limit,
            &w.payer_hex,
            WHO,
        ) {
            Ok(r) => r,
            Err(_) => continue,
        };
        let reply = RegisterReply::pending(plan.next_leaf_index, w.rate_limit, Some(&send_result));
        w.tx_hash = send_result.into_tx_hash();
        reg_in_flight(|m| m.insert(w.reg_key, (reply, Instant::now())));
    }
    // The entry goes with its watcher: a re-send refreshed its timestamp, so
    // left alone it would answer "pending" for up to another TTL with nobody
    // watching the chain for it.
    reg_in_flight(|m| m.remove(&w.reg_key));
    eprintln!(
        "{WHO}: no membership within {}s",
        REG_IN_FLIGHT_TTL.as_secs()
    );
}

